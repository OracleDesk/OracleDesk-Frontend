// Pure helpers for the i18n catalog checker (scripts/i18n-check.mjs) and its tests.
import { parse, TYPE } from "@formatjs/icu-messageformat-parser";
import { printAST } from "@formatjs/icu-messageformat-parser/printer.js";

/** Marker a non-English catalog may use to list keys it has not translated yet. */
export const FALLBACK_MARKER = "$fallback";

/** Flattens nested catalog objects to dot-joined keys -> message strings. */
export function flatten(catalog, prefix = "") {
  const out = {};
  for (const [key, value] of Object.entries(catalog)) {
    if (key === FALLBACK_MARKER) continue;
    const path = prefix ? `${prefix}.${key}` : key;
    if (typeof value === "string") out[path] = value;
    else if (value && typeof value === "object") Object.assign(out, flatten(value, path));
    else throw new Error(`Catalog value at "${path}" must be a string or an object`);
  }
  return out;
}

/** Parses a message as ICU MessageFormat; returns the AST or throws with the key for context. */
export function parseMessage(key, message) {
  try {
    return parse(message, { ignoreTag: true });
  } catch (error) {
    throw new Error(`Invalid ICU message at "${key}": ${error instanceof Error ? error.message : String(error)}`);
  }
}

/**
 * Collects the arguments a message needs: name -> "string" | "number" | "date".
 * select arguments are strings, plural/number arguments are numbers.
 */
export function collectParams(ast, into = new Map()) {
  const note = (name, kind) => {
    const previous = into.get(name);
    // A number or date usage is more specific than a plain argument.
    if (previous === undefined || previous === "string") into.set(name, kind);
  };
  for (const el of ast) {
    switch (el.type) {
      case TYPE.argument:
        note(el.value, "string");
        break;
      case TYPE.number:
        note(el.value, "number");
        break;
      case TYPE.date:
      case TYPE.time:
        note(el.value, "date");
        break;
      case TYPE.select:
        note(el.value, "select");
        for (const option of Object.values(el.options)) collectParams(option.value, into);
        break;
      case TYPE.plural:
        note(el.value, "number");
        for (const option of Object.values(el.options)) collectParams(option.value, into);
        break;
      default:
        break;
    }
  }
  return into;
}

/** TypeScript source for the typed params of every key (`undefined` when a message takes none). */
export function renderParamTypes(messages) {
  const lines = ["// GENERATED by scripts/i18n-check.mjs --write. Do not edit by hand.", "export interface MessageParamTypes {"];
  for (const key of Object.keys(messages).sort()) {
    const params = collectParams(parseMessage(key, messages[key]));
    if (params.size === 0) {
      lines.push(`  ${JSON.stringify(key)}: undefined;`);
      continue;
    }
    const fields = [...params.entries()]
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([name, kind]) => `${name}: ${kind === "number" ? "number" : kind === "date" ? "Date | number" : "string | number"}`);
    lines.push(`  ${JSON.stringify(key)}: { ${fields.join("; ")} };`);
  }
  lines.push("}", "");
  return lines.join("\n");
}

/**
 * Compares a catalog to the English one. Returns human-readable problems:
 * missing keys (unless listed under the fallback marker), extra keys,
 * invalid ICU, and parameter mismatches.
 */
export function compareCatalogs(name, englishFlat, catalog) {
  const problems = [];
  let flat;
  try {
    flat = flatten(catalog);
  } catch (error) {
    return [`${name}: ${error.message}`];
  }
  const fallback = new Set(Array.isArray(catalog[FALLBACK_MARKER]) ? catalog[FALLBACK_MARKER] : []);
  for (const key of Object.keys(englishFlat)) {
    if (!(key in flat)) {
      if (!fallback.has(key)) problems.push(`${name}: missing key "${key}"`);
    } else if (fallback.has(key)) {
      problems.push(`${name}: "${key}" is translated but still listed under ${FALLBACK_MARKER}`);
    }
  }
  for (const key of Object.keys(flat)) {
    if (!(key in englishFlat)) problems.push(`${name}: unknown key "${key}" (not in en.json)`);
  }
  for (const [key, message] of Object.entries(flat)) {
    let ast;
    try {
      ast = parseMessage(key, message);
    } catch (error) {
      problems.push(`${name}: ${error.message}`);
      continue;
    }
    if (!(key in englishFlat)) continue;
    const expected = [...collectParams(parseMessage(key, englishFlat[key])).keys()].sort().join(",");
    const actual = [...collectParams(ast).keys()].sort().join(",");
    if (expected !== actual) problems.push(`${name}: "${key}" uses arguments {${actual}} but en.json uses {${expected}}`);
  }
  return problems;
}

/**
 * Keys never referenced from source. `sources` is the concatenated source
 * text; `dynamicPrefixes` are namespaces looked up by computed key (error codes).
 */
export function findUnusedKeys(keys, sources, dynamicPrefixes = []) {
  const used = new Set();
  const re = /\b(?:t|translate|translateUnsafe|tr)\(\s*(?:[A-Za-z_.]+,\s*)?["'`]([A-Za-z0-9_.-]+)["'`]/g;
  for (const match of sources.matchAll(re)) used.add(match[1]);
  const keyProp = /\b(?:labelKey|messageKey|titleKey|descriptionKey|key)\s*[:=]\s*["'`]([A-Za-z0-9_.-]+)["'`]/g;
  for (const match of sources.matchAll(keyProp)) used.add(match[1]);
  return keys.filter((key) => !used.has(key) && !dynamicPrefixes.some((prefix) => key.startsWith(prefix)));
}

const ACCENTS = {
  a: "à", b: "ƀ", c: "ç", d: "ð", e: "é", f: "ƒ", g: "ĝ", h: "ĥ", i: "ï", j: "ĵ", k: "ķ", l: "ļ", m: "ɱ",
  n: "ñ", o: "ö", p: "þ", q: "ǫ", r: "ŕ", s: "š", t: "ţ", u: "û", v: "ṽ", w: "ŵ", x: "ẋ", y: "ý", z: "ž",
  A: "À", B: "Ɓ", C: "Ç", D: "Ð", E: "É", F: "Ƒ", G: "Ĝ", H: "Ĥ", I: "Ï", J: "Ĵ", K: "Ķ", L: "Ļ", M: "Ṁ",
  N: "Ñ", O: "Ö", P: "Þ", Q: "Ǫ", R: "Ŕ", S: "Š", T: "Ţ", U: "Û", V: "Ṽ", W: "Ŵ", X: "Ẋ", Y: "Ý", Z: "Ž",
};

const accent = (text) => text.replace(/[A-Za-z]/g, (ch) => ACCENTS[ch] ?? ch);

function pseudoAst(ast) {
  return ast.map((el) => {
    if (el.type === TYPE.literal) return { ...el, value: accent(el.value) };
    if (el.type === TYPE.select || el.type === TYPE.plural) {
      const options = {};
      for (const [name, option] of Object.entries(el.options)) options[name] = { ...option, value: pseudoAst(option.value) };
      return { ...el, options };
    }
    return el;
  });
}

/** Accented, ~30% longer version of a message that keeps every ICU argument intact. */
export function pseudoLocalize(key, message) {
  const visibleLength = message.replace(/\{[^{}]*\}/g, "").length;
  const filler = "~".repeat(Math.max(1, Math.ceil(visibleLength * 0.3)));
  const ast = pseudoAst(parseMessage(key, message));
  return `[${printAST(ast)}${filler}]`;
}

/** Rebuilds the nested catalog shape of `source` with every string replaced by `map(path, value)`. */
export function mapCatalog(source, map, prefix = "") {
  const out = {};
  for (const [key, value] of Object.entries(source)) {
    if (key === FALLBACK_MARKER) continue;
    const path = prefix ? `${prefix}.${key}` : key;
    out[key] = typeof value === "string" ? map(path, value) : mapCatalog(value, map, path);
  }
  return out;
}
